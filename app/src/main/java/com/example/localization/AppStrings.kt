fun stringsFor(language: AppLanguage): AppStrings = when (language) {
    AppLanguage.ENGLISH -> EnglishStrings
    AppLanguage.HINDI -> HindiStrings
}

fun categoryLabel(category: VideoCategory, language: AppLanguage): String =
    if (language == AppLanguage.HINDI) category.displayHi else category.displayEn

fun sortLabel(sortOrder: FeedSortOrder, strings: AppStrings): String = when (sortOrder) {
    FeedSortOrder.LATEST -> strings.sortLatest
    FeedSortOrder.MOST_VIEWED -> strings.sortMostViewed
    FeedSortOrder.MOST_LIKED -> strings.sortMostLiked
}

val LocalAppStrings = staticCompositionLocalOf { EnglishStrings }
